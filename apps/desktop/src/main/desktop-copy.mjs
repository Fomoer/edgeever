// The desktop main process runs without the web app's i18next catalogs, so
// its text lives here, keyed by the same locale codes as
// packages/shared/src/i18n. Every locale must provide every key; the tests
// compare them with English and the resolver with the shared one.

export const desktopLocales = ["zh-CN", "en-US", "ja", "pl", "ru"];

/** Same matching as `matchSupportedLocale` in @edgeever/shared; English otherwise. */
export const resolveDesktopLocale = (locale) => {
  const normalized = typeof locale === "string" ? locale.trim().replaceAll("_", "-").toLowerCase() : "";
  const language = normalized.split("-")[0];
  if (language === "zh") return "zh-CN";
  if (language === "ja" || language === "pl" || language === "ru") return language;
  return "en-US";
};

